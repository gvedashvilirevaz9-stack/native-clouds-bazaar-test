export function gt(lang: Lang | string, key: GarageKey, vars?: Record<string, string | number>): string {
  const L = garageLang(lang);
  let s: string = (lang === 'ka' ? readableKa[key] : undefined) ?? garageDict[L][key] ?? garageDict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  return s;
}

export function useGarageT() {
  const {lang} = useLang();
  const L = garageLang(lang);
  const t = (key: GarageKey, vars?: Record<string, string | number>) => gt(lang, key, vars);
  const locale = L === 'ru' ? 'ru-RU' : 'en-GB';
  return {t, lang: L, portalLang: lang, locale};
}

